/**
 * Demo mode: `CURLEW_DEMO=1 curlew window` (or `curlew demo`) opens the window on made-up data, for
 * screenshots, tests and trying Curlew without accounts. The data is generated into a scratch
 * directory and the process is pointed at it, so the real index, config and accounts stay untouched.
 */

import { existsSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

import { DEMO_VERSION, generateDemo } from './generate.ts';

export { DEMO_ACCOUNTS } from './accounts.ts';
export { demoActive } from './active.ts';
export { DEMO_VERSION, generateDemo, type DemoSummary } from './generate.ts';

/** `$CURLEW_DEMO_DIR`, or `<cache home>/curlew-demo`. */
export function demoDir(env: NodeJS.ProcessEnv = process.env): string {
  const explicit = env.CURLEW_DEMO_DIR?.trim();
  if (explicit) return explicit;
  const cache = env.XDG_CACHE_HOME?.trim();
  return join(cache && cache.startsWith('/') ? cache : join(homedir(), '.cache'), 'curlew-demo');
}

/** Generated by this version of the code, and complete? */
export function demoIsFresh(dir: string): boolean {
  try {
    const stamp = JSON.parse(readFileSync(join(dir, 'demo.json'), 'utf8')) as { version?: number };
    return (
      stamp.version === DEMO_VERSION &&
      existsSync(join(dir, 'index.db')) &&
      existsSync(join(dir, 'config.json'))
    );
  } catch {
    return false;
  }
}

/**
 * Switch the process to demo data: generate it when missing or stale, then point the index, config
 * and preview cache at it. Call before anything reads them.
 */
export function prepareDemo(env: NodeJS.ProcessEnv = process.env): string {
  const dir = demoDir(env);
  if (!demoIsFresh(dir)) generateDemo(dir);
  env.CURLEW_DEMO = '1';
  env.CURLEW_DB_PATH = join(dir, 'index.db');
  env.CURLEW_CONFIG = join(dir, 'config.json');
  env.CURLEW_PREVIEWS_DIR = join(dir, 'previews');
  env.CURLEW_AVATARS_DIR = join(dir, 'avatars');
  env.CURLEW_DATA_DIR = dir;
  env.CURLEW_SECRETS_DIR = join(dir, 'secrets');
  return dir;
}
