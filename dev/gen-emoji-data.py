#!/usr/bin/env python3
"""Regenerate app/src/window/emoji-data.ts from Unicode emoji-test.txt and the CLDR annotations.

  dev/gen-emoji-data.py <emoji-test.txt> <cldr/common> > app/src/window/emoji-data.ts

Skin-tone variants are left out (the picker offers the base emoji). Data: Unicode, Inc., under the
Unicode License v3 (SPDX Unicode-3.0), see docs/design/emoji-picker.md.
"""

import json
import re
import sys
import xml.etree.ElementTree as ET

FE0F = "\ufe0f"
SKIN = re.compile("[\U0001f3fb-\U0001f3ff]")

ICONS = {
    "Smileys & Emotion": "😀",
    "People & Body": "👋",
    "Animals & Nature": "🐻",
    "Food & Drink": "🍎",
    "Travel & Places": "🚗",
    "Activities": "⚽",
    "Objects": "💡",
    "Symbols": "❤",
    "Flags": "🏁",
}


def annotations(common, lang):
    out = {}
    for sub in ("annotations", "annotationsDerived"):
        try:
            root = ET.parse(f"{common}/{sub}/{lang}.xml").getroot()
        except FileNotFoundError:
            continue
        for node in root.iter("annotation"):
            cp = node.get("cp").replace(FE0F, "")
            entry = out.setdefault(cp, {"tts": "", "kw": ""})
            if node.get("type") == "tts":
                entry["tts"] = node.text or ""
            else:
                entry["kw"] = node.text or ""
    return out


def text(entry):
    if not entry:
        return ""
    parts = [entry["tts"]] + [k.strip() for k in entry["kw"].split("|") if k.strip()]
    seen = []
    for p in parts:
        if p and p not in seen:
            seen.append(p)
    return " | ".join(seen)


def main(test_path, common):
    en, de = annotations(common, "en"), annotations(common, "de")
    groups = []
    for line in open(test_path, encoding="utf-8"):
        if line.startswith("# group:"):
            groups.append((line.split(":", 1)[1].strip(), []))
            continue
        m = re.match(r"^[0-9A-F ]+;\s*fully-qualified\s*# (\S+) E[\d.]+ (.*)$", line)
        if not m or not groups or SKIN.search(m.group(1)):
            continue
        char, name = m.group(1), m.group(2)
        key = char.replace(FE0F, "")
        groups[-1][1].append((char, text(en.get(key)) or name, text(de.get(key))))
    groups = [(n, e) for n, e in groups if e]
    print("// Generated by dev/gen-emoji-data.py from Unicode emoji-test.txt and the CLDR annotations")
    print("// (Unicode, Inc., Unicode License v3, SPDX Unicode-3.0). Do not edit by hand.")
    print()
    print("/** One entry per line: `emoji<TAB>English name | keywords<TAB>German name | keywords`. */")
    print("export const EMOJI_DATA: readonly { id: string; icon: string; entries: string }[] = [")
    for name, entries in groups:
        ident = re.sub(r"[^a-z]+", "-", name.lower()).strip("-")
        body = "\n".join(f"{c}\t{e}\t{d}" for c, e, d in entries)
        print(f"  {{ id: '{ident}', icon: '{ICONS[name]}', entries: {json.dumps(body, ensure_ascii=False)} }},")
    print("];")


main(sys.argv[1], sys.argv[2])
